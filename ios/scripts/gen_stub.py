#!/usr/bin/env python3
# iOS port.
#
# Generates a C file with one definition per function the ntgcalls C header declares, each
# answering "not built": NTG_ERR_UNKNOWN for an ntg_result, NULL for a pointer, nothing for void.
# ntg_get_version() and ntg_last_error() name the stub. It backs a slice that could not be built
# for real, so an app still links and runs and takes its other path.
#
# Usage: gen_stub.py <ntgcalls.h> <out.c> <version string>

import re
import sys

DECL = re.compile(r"NTG_C_EXPORT\s+([^;(]*?)\b(ntg_\w+)\s*\(([^;]*?)\)\s*;", re.S)


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: gen_stub.py <ntgcalls.h> <out.c> <version>")
    header, out, version = sys.argv[1:]
    with open(header, encoding="utf-8") as f:
        text = f.read()
    lines = [
        "// @generated by ios/scripts/gen_stub.py from ntgcalls.h: regenerate, do not edit.",
        "#define NTG_EXPORTS",
        '#include "ntgcalls.h"',
        "",
        f'static const char* const kStubVersion = "{version}";',
        "",
    ]
    count = 0
    for ret, name, params in DECL.findall(text):
        ret = " ".join(ret.split())
        params = " ".join(params.split()) or "void"
        if name == "ntg_get_version":
            body = "return kStubVersion;"
        elif name == "ntg_last_error":
            body = 'return "ntgcalls is not built for this platform";'
        elif ret == "void":
            body = ""
        elif ret == "ntg_result":
            body = "return NTG_ERR_UNKNOWN;"
        elif ret.endswith("*"):
            body = "return NULL;"
        else:
            raise SystemExit(f"{name}: no stub answer for return type {ret!r}")
        lines.append(f"{ret} {name}({params}) {{ {body} }}".replace("{  }", "{}"))
        count += 1
    if count == 0:
        raise SystemExit("no declarations found")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"stub: {count} functions")


if __name__ == "__main__":
    main()
